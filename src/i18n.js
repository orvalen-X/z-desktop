const SUPPORTED = Object.keys(STRINGS);

// Prefer the language the person chose inside Z (remembered by the wrapper), then the computer's language.
function pickLang(preferred, systemLocales) {
  const list = [preferred, ...(systemLocales || [])].filter(Boolean);
  for (const tag of list) {
    const base = String(tag).toLowerCase().split(/[-_]/)[0];
    if (base === 'iw') return 'he';
    if (SUPPORTED.includes(base)) return base;
  }
  return 'en';
}

function strings(lang) {
  return STRINGS[lang] || STRINGS.en;
}

module.exports = { STRINGS, SUPPORTED, pickLang, strings };
